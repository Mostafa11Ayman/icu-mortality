"""ICU in-hospital mortality: Streamlit demo.

Run from the repo root:
    streamlit run app/streamlit_app.py

All logic lives in src/ (predict.py reuses the cleaning and feature code from
features.py), so the demo scores a record exactly like the notebooks do.
"""
import json
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from src.predict import RecordError, load_artifacts, score_text  # noqa: E402

EXAMPLES = ROOT / "app" / "examples"
FIGURES = ROOT / "reports" / "figures"

st.set_page_config(page_title="ICU mortality risk (research demo)", layout="wide")


@st.cache_resource
def artifacts():
    return load_artifacts(ROOT)


model, meta = artifacts()
THRESHOLD = meta["threshold"]["value"]

st.title("ICU in-hospital mortality from the first 48 hours")
st.warning(
    "**Research and portfolio demo. Not for clinical use.** The model was developed and tested on "
    "the public PhysioNet/CinC Challenge 2012 data only and has not been externally or prospectively validated."
)


def show_result(text: str, label: str):
    try:
        r = score_text(model, meta, text)
    except RecordError as e:
        st.error(f"Cannot score this record: {e}")
        return
    except Exception as e:  # noqa: BLE001
        st.error(f"Unexpected problem while reading the record ({type(e).__name__}). Is it a PhysioNet 2012 record?")
        return

    c1, c2, c3 = st.columns(3)
    c1.metric("Predicted in-hospital mortality", f"{r['risk']:.1%}")
    c2.metric("Frozen alert threshold", f"{THRESHOLD:.1%}")
    c3.metric("Alert", "HIGH RISK" if r["flag"] else "below threshold")
    st.caption(
        f"{label}. Average mortality in the data is about 14%. The threshold was chosen on the development "
        "set to catch 80% of deaths; on the test set it caught 81% of deaths and 41% of flagged patients died."
    )

    contrib = r["contributions"]
    top = contrib.head(12)[::-1]
    fig, ax = plt.subplots(figsize=(7, 4.5))
    ax.barh(top.index, top.values, color=np.where(top.values > 0, "#E45756", "#4C78A8"))
    ax.axvline(0, color="grey", lw=0.8)
    ax.set_xlabel("Contribution to log-odds of death (red raises risk, blue lowers it)")
    ax.set_title("What drives this prediction (12 largest variables)")
    plt.tight_layout()
    left, right = st.columns([3, 2])
    left.pyplot(fig)
    right.markdown(
        "Each bar is one measured variable, with all its features (lowest, highest, mean, last value, "
        "number of measurements and whether it was measured) added together. The model is a logistic "
        "regression, so these contributions are exact: the starting point (average patient) plus all bars "
        "gives this patient's prediction. They show association, not cause."
    )
    feats = r["features"].T.rename(columns={0: "value"})
    with right.expander("Key values used by the model"):
        keys = ["Age", "Gender", "Weight_admit", "MechVent_ever", "GCS_last", "GCS_min", "BUN_last",
                "Creatinine_max", "Urine_mean", "Lactate_last", "HCO3_last", "HR_mean", "Temp_mean"]
        st.dataframe(feats.loc[[k for k in keys if k in feats.index]], width="stretch")
    removed = int(r["cleaning"]["removed"].sum())
    if removed:
        right.info(f"{removed} physically impossible value(s) were removed by the cleaning rules.")


tab_pred, tab_ex, tab_res, tab_about = st.tabs(["Predict", "Examples", "Results", "About"])

with tab_pred:
    st.subheader("Score one ICU stay")
    st.markdown(
        "Upload one record in the PhysioNet 2012 format: a text file with the header `Time,Parameter,Value`, "
        "the descriptors (Age, Gender, Height, ICUType, Weight) at `00:00`, then measurements up to `48:00`."
    )
    up = st.file_uploader("PhysioNet 2012 record (.txt)", type=["txt", "csv"])
    if up is not None:
        show_result(up.getvalue().decode("utf-8", errors="replace"), f"File: {up.name}")

with tab_ex:
    st.subheader("Synthetic example patients")
    st.markdown("These patients are **invented** (generated by `app/make_examples.py`), not real PhysioNet records.")
    files = sorted(EXAMPLES.glob("*.txt"))
    names = {f.stem.replace("example_", "").replace("_", " "): f for f in files}
    choice = st.radio("Choose an example", list(names), horizontal=True)
    if choice:
        text = names[choice].read_text()
        show_result(text, f"Synthetic example: {choice}")
        with st.expander("Show the raw record"):
            st.code(text[:3000] + ("\n..." if len(text) > 3000 else ""), language="text")

with tab_res:
    st.subheader("Results on the held-out test set (set-c, scored once)")
    m = json.loads((ROOT / "reports" / "test_metrics.json").read_text())
    res = pd.DataFrame({
        "AUROC [95% CI]": [f"{m['model']['AUROC']:.3f} [{m['model']['AUROC_lo']:.3f}, {m['model']['AUROC_hi']:.3f}]",
                           f"{m['saps_i']['AUROC']:.3f} [{m['saps_i']['AUROC_lo']:.3f}, {m['saps_i']['AUROC_hi']:.3f}]"],
        "AUPRC [95% CI]": [f"{m['model']['AUPRC']:.3f} [{m['model']['AUPRC_lo']:.3f}, {m['model']['AUPRC_hi']:.3f}]",
                           f"{m['saps_i']['AUPRC']:.3f} [{m['saps_i']['AUPRC_lo']:.3f}, {m['saps_i']['AUPRC_hi']:.3f}]"],
        "n": [m["n_test"], m["saps_i_subset_n"]],
    }, index=["Model (logistic regression)", "SAPS-I"])
    st.table(res)
    t = m["threshold"]
    st.markdown(
        f"At the frozen threshold: sensitivity **{t['sensitivity']:.0%}**, specificity **{t['specificity']:.0%}**, "
        f"PPV **{t['PPV']:.0%}**, NPV **{t['NPV']:.0%}**, {t['flagged_%']:.0f}% of stays flagged. "
        f"Calibration: mean predicted {m['calibration_model']['mean predicted']:.1%} vs observed "
        f"{m['calibration_model']['observed']:.1%}, slope {m['calibration_model']['slope']:.2f}."
    )
    c1, c2 = st.columns(2)
    c1.image(str(FIGURES / "05_calibration_test.png"), caption="Calibration on the test set")
    c2.image(str(FIGURES / "05_subgroups_test.png"), caption="AUROC by subgroup, model vs SAPS-I")
    c1.image(str(FIGURES / "05_shap_by_variable.png"), caption="Most important variables (SHAP, test set)")
    c2.image(str(FIGURES / "03_mortality_by_age_icu.png"), caption="Mortality by age and ICU type (development set)")

with tab_about:
    st.subheader("About this project")
    st.markdown(
        """
**Question.** Can the first 48 hours of an ICU stay predict in-hospital death better than SAPS-I?

**Data.** PhysioNet/CinC Challenge 2012: 12,000 ICU stays (set-a, set-b, set-c), open access under the
Open Data Commons Attribution License v1.0. Silva I, Moody G, Scott DJ, Celi LA, Mark RG. *Predicting in-hospital
mortality of ICU patients: The PhysioNet/Computing in Cardiology Challenge 2012.* Computing in Cardiology 2012;39:245-248.

**Method.** Per stay and variable: lowest, highest, mean and last value, number of measurements and a measured/not
measured flag (225 features). Trained on set-a and set-b with nested 5-fold cross-validation; logistic regression,
random forest and LightGBM compared; the simplest model not significantly worse than the best was chosen. The alert
threshold was frozen on the development set, and set-c was scored once.

**Limitations.** One data source from around 2012 with no external validation; prediction only at 48 h for stays of
at least 48 h; ages capped at 90; stays with no measurements excluded; explanations show association, not cause.
"""
    )
